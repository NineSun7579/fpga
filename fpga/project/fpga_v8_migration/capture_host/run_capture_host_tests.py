"""Compile C++17 and replay the real helper's fixture through preserved RTL.
No hardware/driver I/O; every generated byte stays in capture_host/artifacts.
"""
from __future__ import annotations
from collections import defaultdict
from pathlib import Path
import hashlib
import importlib.util
import json
import os
import re
import subprocess
import sys

sys.dont_write_bytecode=True
HERE=Path(__file__).resolve().parent
ART=HERE/"artifacts"
MIGRATION=HERE.parent
CONTROL=MIGRATION/"capture_endpoint"


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def manifest():
    protected=[]
    for directory in ("cooperative_host","cooperative_endpoint","capture_endpoint"):
        protected.extend(p for p in (MIGRATION/directory).rglob("*") if p.is_file())
    protected.extend(MIGRATION/name for name in (
        "cooperative_control/fpga_v8_coop_control_axil.v",
        "capture_lease/fpga_v8_capture_lease.v","capture_lease/fpga_v8_capture_ov5640_ddr.v"))
    return {str(p.relative_to(MIGRATION)).replace("\\","/"):sha(p) for p in protected}
def run(command,name,cwd=HERE):
    p=subprocess.run(command,cwd=cwd,capture_output=True,text=True,timeout=120)
    text=p.stdout+p.stderr;(ART/name).write_text(text,encoding="utf-8")
    if p.returncode or "** Error" in text or "** Fatal" in text:raise RuntimeError(f"{command}\n{text}")
    return text


def main():
    ART.mkdir(exist_ok=True)
    before=manifest()
    initial=ART/"protected_hashes_initial.json"
    if initial.exists():assert json.loads(initial.read_text())==before,"protected sibling changed since initial scan"
    else:initial.write_text(json.dumps(before,indent=2)+"\n")
    (ART/"protected_hashes_before.json").write_text(json.dumps(before,indent=2)+"\n")
    commands=[["cmd.exe","/d","/c",str(HERE/"build_local_selftest.cmd")]]
    compile_log=run(commands[-1],"compile.txt")
    assert re.search(r"\b19\.\d+\.\d+",compile_log),compile_log
    binary=ART/"capture_host_selftest.exe"
    commands.append([str(binary),"--fixture",str(ART/"host.fixture")])
    log=run(commands[-1],"selftest.txt")
    marker=re.search(r"CAPTURE_HOST_PASS cases=(\d+) checks=(\d+) writes=(\d+) reads=(\d+) dma=(\d+)",log)
    assert marker,log
    counts=dict(zip(("cases","checks","writes","reads","dma"),map(int,marker.groups())))
    commands.append([str(binary),"--map"])
    mapping_stdout=run(commands[-1],"host_map.txt")
    actual_map={name:(int(local,16),int(physical,16)) for name,local,physical in
                (line.split() for line in mapping_stdout.splitlines())}
    mapping=json.loads((CONTROL/"register_map.json").read_bytes())
    expected_map={r["name"]:(int(r["local_offset"],16),int(r["physical_address"],16)) for r in mapping["registers"]}
    assert actual_map==expected_map and len(actual_map)==32
    assert mapping["status_bits"]["10"].startswith("offered host bank")
    assert mapping["dma_len"]==0 and mapping["dma_size"]==4 and mapping["slot_bytes"]==16
    api=json.loads((HERE/"host_api.json").read_text())
    assert api["raw_payload_bytes"]==614400 and api["output_payload_bytes"]==1228800
    assert api["copy_tag"] is False and api["accepted_generation"]=="local 0x170"
    assert api["accepted_config_count"]=="local 0x174"

    # Read the final controller's independent oracle and harness; do not execute
    # its runner or write/import pycache to the sibling directory.
    spec=importlib.util.spec_from_file_location("capture_host_control_oracle",CONTROL/"run_tests.py")
    module=importlib.util.module_from_spec(spec);sys.modules[spec.name]=module;spec.loader.exec_module(module)
    suite=module.Suite();suite.reset()
    fixture_counts=defaultdict(int);dma_records=[]
    for line in (ART/"host.fixture").read_text().splitlines():
        code,*fields=line.split();values=[int(v,16) for v in fields];fixture_counts[code]+=1
        if code in ("R","W"):
            physical,value,response=values
            assert physical%16==0 and 0x40010000<=physical<0x40011000
            local=(physical-0x40010000)//4
            if code=="R":
                predicted=suite.m.cap_read(local) if local>=0x100 else suite.m.coop_read(local)
                assert predicted==(value,response),(line,predicted)
                suite.read(local,label="C++ RAW/paired-output helper observed register")
            else:
                predicted=suite.write(local,value,label="C++ RAW/paired-output helper singleton")
                assert predicted==response,(line,predicted)
        elif code=="S":suite.sof(values[0])
        elif code=="P":suite.publish(values[0])
        elif code=="E":suite.enable_coop(values[0])
        elif code=="D":suite.done()
        elif code=="F":
            address,offset,length=values
            if length==614400:
                assert suite.m.bound is not None and address==suite.m.bound.addr and offset==0x1000
            else:
                assert length==1228800 and suite.m.outhost is not None
                assert address==0x08000000+suite.m.outhost*0x200000 and offset==0x1000+614400
            dma_records.append(dict(address=address,reserved_rx_offset=offset,bytes=length))
        else:raise AssertionError(line)
    assert fixture_counts["P"]==2 and fixture_counts["F"]==4 and fixture_counts["D"]==2
    assert suite.m.bound is None and suite.m.cap==[0,0] and suite.m.out==[0,0]
    assert suite.m.gen==0x22334455 and suite.m.accepted_config==2
    (ART/"stimulus.txt").write_text("".join(str(code)+" "+" ".join(f"{v:x}" for v in args)+"\n"
        for code,args in suite.ops),encoding="ascii")
    (ART/"expected.trace").write_text("".join(f"{op} {ch}"+"".join(f" {v:x}" for v in event)+"\n"
        for (op,ch),events in suite.expected.items() for event in events),encoding="ascii")
    tb=(CONTROL/"tb_fpga_v8_capture_endpoint.sv").read_bytes().replace(
        b"module tb_fpga_v8_capture_endpoint;",b"module tb_fpga_v8_capture_host_fixture;")
    assert b"module tb_fpga_v8_capture_host_fixture;" in tb
    local_tb=ART/"tb_fpga_v8_capture_host_fixture.sv"
    # Byte-based declaration scan before creating/replacing the unique local
    # simulation top; source encodings elsewhere need not be decoded.
    declaration_hits=[]
    for path in MIGRATION.parent.rglob("*"):
        if path.suffix.lower() in (".v",".sv",".vh") and path.resolve()!=local_tb.resolve():
            if re.search(rb"\bmodule\s+tb_fpga_v8_capture_host_fixture\b",path.read_bytes()):
                declaration_hits.append(str(path))
    assert not declaration_hits,declaration_hits
    local_tb.write_bytes(tb)
    sim=Path(os.environ.get("MODELSIM_BIN",r"C:\modeltech64_10.6e\win64"))
    rtl=[MIGRATION/name for name in (
        "cooperative_endpoint/fpga_v8_coop_axi128_endpoint.v","cooperative_control/fpga_v8_coop_control_axil.v",
        "capture_lease/fpga_v8_capture_lease.v","capture_endpoint/fpga_v8_capture_control_axil.v",
        "capture_endpoint/fpga_v8_coop_axil_router.v")]
    sim_commands=[[str(sim/"vlib.exe"),"work_capture_host"],
        [str(sim/"vlog.exe"),"-work","work_capture_host",*map(str,rtl)],
        [str(sim/"vlog.exe"),"-sv","-work","work_capture_host",str(ART/"tb_fpga_v8_capture_host_fixture.sv")],
        [str(sim/"vsim.exe"),"-c","-onfinish","stop","work_capture_host.tb_fpga_v8_capture_host_fixture",
         "-do","run -all; quit -f"]]
    logs=[]
    for i,command in enumerate(sim_commands):commands.append(command);logs.append(run(command,f"modelsim_{i}.txt",ART))
    assert "CAPTURE_ENDPOINT_PASS" in logs[-1],logs[-1]
    actual=defaultdict(list)
    for line in (ART/"actual.trace").read_text().splitlines():
        fields=line.split();actual[(int(fields[0]),fields[1])].append(tuple(int(v,16) for v in fields[2:]))
    mismatches=[]
    for key in sorted(set(actual)|set(suite.expected)):
        if actual[key]!=suite.expected[key]:mismatches.append(f"{key} expected {suite.expected[key][:3]} got {actual[key][:3]}")
    (ART/"comparison.txt").write_text("\n".join(mismatches) if mismatches else
        f"PASS: {sum(map(len,actual.values()))} public events match C++ fixture and independent Python ownership oracle.\n")
    assert not mismatches,"\n".join(mismatches[:20])
    after=manifest();(ART/"protected_hashes_after.json").write_text(json.dumps(after,indent=2)+"\n")
    assert before==after,"protected helper/controller/endpoint/artifact mutation"
    report=dict(status="PASS",scope="pure host contracts and actual-manager/control-chain fixture; no physical DMA/frame validation",
        compiler="MSVC 19 C++17 /W4 /WX",counts=counts,commands=commands,
        crossfixture=dict(status="PASS",registers_checked=32,operations=len(suite.ops),
                          public_events=sum(map(len,actual.values())),fixture_counts=dict(fixture_counts),
                          planned_dma_records=dma_records),protected_files=len(before),protected_hashes_unchanged=True,
        candidate_hashes={p.name:sha(p) for p in HERE.iterdir() if p.is_file()},
        trace_hashes={p.name:sha(p) for p in (ART/"host.fixture",ART/"actual.trace",ART/"expected.trace")})
    (ART/"results.json").write_text(json.dumps(report,indent=2)+"\n")
    print(log,end="");print(json.dumps({k:report[k] for k in ("status","counts","crossfixture","protected_files")},indent=2))


if __name__=="__main__":main()
