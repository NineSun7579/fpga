HERE = Path(__file__).resolve().parent
BUILD = HERE.parent / 'source_diagnostics_timing_build_03'
HELPER = HERE.parents[2] / 'tools' / 'cam3_i2c_pt.py'
HELPER_SHA = '0aee346c3ef22318a68592728e0494b223b2422398da4b831b8f38af84dca2b5'
RTL_SHA = {
    'v7_sdt_bus.v': '08822426617f6b77b76780d159808798c0b11843bc1fefb3f21a6c9b6529b292',
    'v7_sfd_candidate.v': 'dd4f6327633ce7f634d71139cd92fbafdce11e2fee5780f940e476540e5b741b',
}
DEVICE = '/dev/pango_pci_driver'
BASE = 0x20001000
STATUS, COMMAND, INDEX, DATA, EPOCH = 0, 0x10, 0x20, 0x30, 0x40
VALID, OVERRUN, AVAILABLE, INVALID = 1, 2, 4, 8
MAGIC = 0x53464401


def require(ok, message):
    if not ok:
        raise ValueError(message)


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def load(path):
    return json.loads(Path(path).read_text(encoding='utf-8-sig'))


def utc():
    return datetime.now(timezone.utc).isoformat()


def artifact(path):
    path = Path(path).resolve(strict=True)
    return {'path': str(path), 'bytes': path.stat().st_size, 'sha256': sha(path)}


def offline_check():
    manifest = load(BUILD / 'manifest.json')
    for name, digest in RTL_SHA.items():
        require(sha(BUILD / 'rtl' / name) == digest == manifest['local_hashes']['rtl/' + name],
                'Frozen build03 RTL/manifest mismatch: ' + name)
    require(sha(HELPER) == HELPER_SHA, 'Fixed-device helper changed; review required')
    return {'status': 'offline_protocol_checked', 'hardware_pass': False,
            'window': ['0x20001000', '0x200013ff'], 'rtl_sha256': RTL_SHA,
            'helper': artifact(HELPER), 'register_offsets': [STATUS, COMMAND, INDEX, DATA, EPOCH]}


def address(camera, offset):
    require(type(camera) is int and 1 <= camera <= 4, 'Camera must be 1..4')
    require(offset in (STATUS, COMMAND, INDEX, DATA, EPOCH), 'Undefined diagnostic register')
    return BASE + (camera - 1) * 0x100 + offset


class UncertainDMA(RuntimeError):
    pass


class RegisterIO:
    """Poison permanently on helper exception/None/non-u32, retain driver reference."""
    def __init__(self, driver, log=lambda row: None):
        self.driver, self.log, self.poisoned = driver, log, False

    def operation(self, direction, addr, value=None):
        require(type(addr) is int and BASE <= addr <= BASE + 0x3ff and addr & 15 == 0,
                'DMA address must be a defined 16-byte aligned diagnostic address')
        require((addr & 255) in (STATUS, COMMAND, INDEX, DATA, EPOCH), 'Undefined slot')
        if self.poisoned:
            raise UncertainDMA('Submissions permanently stopped')
        self.log({'event': 'submit', 'direction': direction, 'address': hex(addr),
                  'length': 16, 'value': value, 'utc': utc()})
        try:
            if direction == 'read':
                result = self.driver.read32(addr)
                if type(result) is not int or not 0 <= result <= 0xffffffff:
                    raise UncertainDMA('Missing/invalid read completion')
            else:
                result = self.driver.write32(addr, value)
                if result is not None and result != 0:
                    raise UncertainDMA('Failed write completion')
        except BaseException as error:
            self.poisoned = True
            raise UncertainDMA('DMA completion uncertain: ' + repr(error)) from error
        self.log({'event': 'completed', 'direction': direction, 'address': hex(addr),
                  'value': result, 'utc': utc()})
        return result

    def rd(self, camera, offset):
        return self.operation('read', address(camera, offset))

    def wr(self, camera, offset, value):
        require(offset in (COMMAND, INDEX) and type(value) is int and
                (value in (1, 2) if offset == COMMAND else 0 <= value < 16), 'Illegal write')
        return self.operation('write', address(camera, offset), value)


def decode(words):
    require(len(words) == 16 and all(type(w) is int and 0 <= w <= 0xffffffff for w in words),
            'Sixteen uint32 words required')
    require(words[15] == MAGIC, 'Source diagnostic format mismatch')
    widths = {1: 24, 2: 16, 3: 16, 4: 24, 5: 24, 6: 24, 7: 24,
              8: 24, 9: 24, 10: 24, 11: 16, 12: 8, 13: 16, 14: 24}
    require(all(words[i] >> width == 0 for i, width in widths.items()), 'Reserved bits nonzero')
    result = dict(zip(('source_sequence', 'source_bytes', 'href_segments', 'odd_href_segments',
                      'aligned_pixels', 'native_pixels', 'valid_vsync_overlap'), words[:7]))
    result.update(tail_gap_cycles=words[7] & 0xffff, previous_source_bytes=words[8],
                  previous_aligned_pixels=words[9], previous_native_pixels=words[10],
                  previous_odd_href_segments=words[11], previous_href_segments=words[13],
                  raw_byte_vsync_overlap=words[14], format=words[15])
    result['flags'] = {name: bool(words[7] & (1 << bit)) for bit, name in enumerate(
        ('armed', 'have_previous', 'seen_href', 'tail_gap_saturated', 'clipped_href',
         'vsync_mismatch', 'counter_overflow', 'bad'), 16)}
    result['boundary_flags'] = {name: bool(words[12] & (1 << bit)) for bit, name in enumerate(
        ('start_native', 'end_native', 'start_aligned', 'end_aligned', 'end_href',
         'previous_start_aligned', 'previous_end_aligned', 'previous_bad'))}
    return result


def snapshot(io, camera, timeout=2.0, poll=0.01, clock=time.monotonic, sleep=time.sleep):
    require(math.isfinite(timeout) and 0 < timeout <= 30 and 0 < poll <= timeout,
            'Bounded timeout/poll required')
    deadline = clock() + timeout
    e0 = io.rd(camera, EPOCH)
    while True:
        status = io.rd(camera, STATUS)
        require(io.rd(camera, EPOCH) == e0, 'Epoch changed during availability wait')
        require(not status & INVALID and e0 != 0xffffffff, 'Invalid diagnostic session')
        require(not status & VALID, 'Unexpected existing lease: owner/session violation')
        if status & AVAILABLE:
            break
        if clock() >= deadline:
            raise TimeoutError('Snapshot unavailable/busy timeout; no acquire submitted')
        sleep(poll)
    io.wr(camera, COMMAND, 1)
    before = io.rd(camera, STATUS)
    require(before & VALID and not before & (INVALID | AVAILABLE), 'ACQUIRE did not establish lease')
    words = []
    for index in range(16):
        if clock() >= deadline:
            raise TimeoutError('Snapshot read deadline exceeded; lease retained')
        io.wr(camera, INDEX, index)
        require(io.rd(camera, INDEX) == index, 'INDEX readback mismatch')
        words.append(io.rd(camera, DATA))
    after = io.rd(camera, STATUS)
    e1 = io.rd(camera, EPOCH)
    require(after & VALID and not after & (INVALID | AVAILABLE) and e0 == e1,
            'Snapshot lease/epoch changed; entire sample rejected')
    values = decode(words)
    io.wr(camera, COMMAND, 2)
    require(not io.rd(camera, STATUS) & (VALID | INVALID), 'RELEASE failed or session reset')
    require(io.rd(camera, EPOCH) == e1, 'Epoch changed at release; sample rejected')
    return {'camera': camera, 'captured_utc': utc(), 'epoch_before': e0, 'epoch_after': e1,
            'status_before': before, 'status_after': after, 'raw_words': words,
            'raw_hex': ['0x%08x' % w for w in words], 'values': values,
            'atomic_scope': 'one_camera_leased_bank', 'normal_frames_proven': False}


def live_identity():
    return {'host': socket.gethostname(),
            'boot_id': Path('/proc/sys/kernel/random/boot_id').read_text().strip()}


def other_device_owners():
    """Fail closed on inaccessible /proc fd inventories; run with sufficient rights."""
    import stat
    device = os.stat(DEVICE)
    owners = []
    for proc in Path('/proc').iterdir():
        if not proc.name.isdigit() or int(proc.name) == os.getpid():
            continue
        try:
            for fd in (proc / 'fd').iterdir():
                try:
                    info = fd.stat()
                except FileNotFoundError:
                    continue
                if stat.S_ISCHR(info.st_mode) and info.st_rdev == device.st_rdev:
                    owners.append({'pid': int(proc.name), 'fd': str(fd)})
        except FileNotFoundError:
            continue
    return owners


def execution_gate(path):
    # Reuse existing offline receipt/raw-program-log validation, never its main.
    from new_program_candidate import bound
    from new_program_candidate import VENDOR
    from new_validate_board import program_time_gate, vendor_parser, utc as parse_utc
    gate = load(path)
    require(gate.get('contract') == 'sourceDiagnosticSession/v1', 'External session gate required')
    files = {k: bound(v) for k, v in gate['artifacts'].items()}
    delivery = load(files['delivery'])
    require(delivery.get('candidate_id') == BUILD.name, 'Only build03 delivery permitted')
    require(delivery.get('contract') == 'validatedDelivery/v1' and delivery.get('status') == 'validated',
            'Accepted validated bit delivery required')
    # Exported evidence may reside on RK while original receipt paths are Windows.
    # Preserve originals as strings; only gate artifact paths are local bound paths.
    receipt, pre = load(files['program_receipt']), load(files['owner_preflight'])
    require(receipt.get('status') == 'success' and receipt.get('mode') == 'sram' and
            receipt.get('target') == 'PG2L100H' and receipt.get('check_only') is False and
            receipt.get('candidate_id') == BUILD.name and
            receipt.get('bit_sha256') == gate['bit_sha256'] == delivery['bitstream']['sha256'] == sha(files['bitstream']) and
            receipt.get('bit_bytes') == delivery['bitstream']['bytes'] == files['bitstream'].stat().st_size and
            receipt.get('delivery_manifest_sha256') == sha(files['delivery']) and
            receipt.get('owner_preflight_sha256') == sha(files['owner_preflight']) and
            receipt.get('programmer_sha256') == sha(VENDOR), 'Actual receipt/bit/delivery binding mismatch')
    require(pre.get('contract') == 'boardOwnerPreflight/v1' and pre.get('accepted') is True and pre.get('reviewer') and
            pre.get('bit_sha256') == gate['bit_sha256'] and
            pre.get('delivery_manifest_sha256') == sha(files['delivery']), 'Reviewed program preflight required')
    require(set(receipt['logs']) == {gate['original_log_paths'][k] for k in
            ('cfg_log', 'server_log', 'client_log')}, 'Original receipt log provenance mismatch')
    parse, error_pattern = vendor_parser()
    stages, errors = parse(files['cfg_log'].read_bytes().decode('gb18030').replace('\r\n', '\n'), 'sram')
    require(not errors and stages == receipt.get('stages') and stages and all(stages.values()) and
            not receipt.get('stage_errors'), 'Raw program stages do not prove completion')
    for key in ('server_log', 'client_log'):
        require(not error_pattern.search(files[key].read_bytes().decode('gb18030')), 'Program log contains errors')
    end = program_time_gate(load(files['program_session']), receipt, pre, files)
    boot = load(files['program_boot'])
    session = load(files['program_session'])
    identity = live_identity()
    require(boot.get('contract') == 'programBootCapture/v1' and boot.get('collector') and
            boot['boot_id'] == identity['boot_id'] == gate['boot_id'] and boot['host'] == identity['host'] == gate['host'] and
            files['program_boot_raw'].read_text().strip() == identity['boot_id'] and
            boot['raw_sha256'] == sha(files['program_boot_raw']) and
            0 <= parse_utc(session['started_utc']) - parse_utc(boot['captured_utc']) <= 60,
            'Programming must be bound to current boot by actual pre-program raw capture')
    owner = load(files['owner_session'])
    now = time.time()
    require(owner.get('contract') == 'exclusiveDiagnosticOwner/v1' and owner.get('reviewer') and
            owner['board_id'] == gate['board_id'] and owner['host'] == identity['host'] and
            owner['boot_id'] == identity['boot_id'] and owner['bit_sha256'] == gate['bit_sha256'] and
            owner['program_receipt_sha256'] == sha(files['program_receipt']) and
            owner['delivery_sha256'] == sha(files['delivery']) and owner['collector_sha256'] == sha(__file__) and
            owner['supervisor_pid'] == os.getppid() and
            end < parse_utc(owner['captured_utc']) <= now < parse_utc(owner['expires_utc']) and
            now - parse_utc(owner['captured_utc']) <= 60 and
            parse_utc(owner['expires_utc']) - parse_utc(owner['captured_utc']) <= 300,
            'Fresh exclusive supervisor/receipt/boot/collector binding required')
    ticks = Path('/proc/%d/stat' % os.getppid()).read_text().rsplit(')', 1)[1].split()[19]
    require(str(owner['supervisor_start_ticks']) == ticks, 'Supervisor PID reused')
    raw = files['owner_session_raw'].read_text().splitlines()
    require(owner['raw_sha256'] == sha(files['owner_session_raw']) and all(
        '%s=%s' % (k, owner[k]) in raw for k in
        ('board_id', 'host', 'boot_id', 'bit_sha256', 'program_receipt_sha256', 'delivery_sha256',
         'collector_sha256', 'supervisor_pid', 'supervisor_start_ticks', 'captured_utc', 'expires_utc')) and
        'session_policy=no_other_device_owner_or_programmer_until_collector_releases' in raw,
        'Exclusive session raw binding/policy missing')
    # No fd holder is not proof that an earlier killed DMA has gone idle.
    # Require an independent, current, line-bound review of actual quiescence.
    review = owner['dma_quiescence_review']
    require(review.get('status') == 'reviewed' and review.get('reviewer') and review.get('note') and
            review.get('boundary_kind') == 'proven_dma_idle' and review.get('references') and
            review['raw_sha256'] == sha(files['owner_dma_boundary_raw']),
            'Current independently reviewed DMA-idle raw evidence required')
    boundary_lines = files['owner_dma_boundary_raw'].read_text().splitlines()
    require('boot_id=' + identity['boot_id'] in boundary_lines and
            'captured_utc=' + owner['captured_utc'] in boundary_lines,
            'DMA boundary capture must belong to this current owner session')
    for ref in review['references']:
        require(type(ref['line']) is int and 1 <= ref['line'] <= len(boundary_lines) and
                ref.get('text') and boundary_lines[ref['line'] - 1] == ref['text'],
                'DMA boundary raw reference mismatch')
    require(not other_device_owners(), 'Viewer/probe/uncertain DMA owner still holds device')
    return gate, files, owner


def hold_buffers(error, output, driver, lock_fd, streams):
    # Deliberately keep every reference/FD/map alive. Never close, free or retry.
    import signal
    for sig in (signal.SIGINT, signal.SIGTERM, signal.SIGHUP):
        signal.signal(sig, signal.SIG_IGN)
    try:
        (output / 'failure.json').write_text(json.dumps({
            'status': 'uncertain_completion_buffers_held', 'pid': os.getpid(),
            'error': repr(error), 'submissions_stopped': True, 'accepted': False}, indent=2))
    finally:
        print('Uncertain DMA: submissions stopped; buffers/FD/owner lock held; do not kill before quiescence.',
              file=sys.stderr, flush=True)
        while True:
            time.sleep(30)


def execute(args):
    import fcntl
    offline_check()
    gate, files, owner = execution_gate(args.gate)
    args.output.mkdir(parents=True, exist_ok=False)
    lock_fd = os.open('/run/lock/pango-source-diagnostic.lock', os.O_CREAT | os.O_RDWR, 0o600)
    fcntl.flock(lock_fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    driver = None
    streams = []
    io = None
    try:
        require(not other_device_owners(), 'Other device owner appeared before open')
        spec = importlib.util.spec_from_file_location('_source03_fixed_pci_helper', HELPER)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        # The real helper's mapping initializer ignores ioctl return codes. Check
        # them at its existing call boundary without replacing any DMA operation.
        from types import SimpleNamespace
        actual_ioctl = module.fcntl.ioctl
        def checked_ioctl(*params):
            result = actual_ioctl(*params)
            if result != 0:
                raise UncertainDMA('Fixed helper ioctl returned nonzero: %r' % result)
            return result
        module.fcntl = SimpleNamespace(ioctl=checked_ioctl)
        # Retain object even if initialization fails after partial allocation.
        driver = module.PciDriver.__new__(module.PciDriver)
        module.PciDriver.__init__(driver)
        operations = (args.output / 'operations.jsonl').open('x', encoding='utf-8')
        streams.append(operations)
        def log(row):
            operations.write(json.dumps(row) + '\n')
            operations.flush()
        io = RegisterIO(driver, log)
        raw_paths = []
        rows = []
        for camera in range(1, 5):
            require(time.time() < datetime.fromisoformat(owner['expires_utc'].replace('Z', '+00:00')).timestamp(),
                    'Exclusive session expired')
            require(not other_device_owners() and live_identity()['boot_id'] == gate['boot_id'],
                    'Owner/boot changed during collection')
            row = snapshot(io, camera, args.timeout)
            path = args.output / ('diag%d.raw.jsonl' % camera)
            row.update(board_id=gate['board_id'], boot_id=gate['boot_id'], bit_sha256=gate['bit_sha256'])
            path.write_text(json.dumps(row) + '\n', encoding='utf-8')
            print(json.dumps(row), flush=True)
            raw_paths.append(path)
            rows.append(row)
        require(not other_device_owners() and live_identity()['boot_id'] == gate['boot_id'] and
                time.time() < datetime.fromisoformat(owner['expires_utc'].replace('Z', '+00:00')).timestamp(),
                'Exclusive owner/boot/session changed at end of collection')
        require(all(sha(p) == gate['artifacts'][k]['sha256'] for k, p in files.items()) and
                load(args.gate) == gate, 'Gate/source evidence changed during collection')
        # Metadata only after all real reads and normal helper close complete.
        try:
            driver.close()
        except BaseException as error:
            hold_buffers(error, args.output, driver, lock_fd, streams)
        driver = None
        operations.close()
        for camera, (path, row) in enumerate(zip(raw_paths, rows), 1):
            meta = {'contract': 'diagnosticCapture/v1', 'collector': str(Path(__file__).resolve()),
                    'collector_sha256': sha(__file__), 'source_camera': camera,
                    'board_id': gate['board_id'], 'host': gate['host'], 'boot_id': gate['boot_id'],
                    'bit_sha256': gate['bit_sha256'], 'captured_utc': row['captured_utc'],
                    'raw_path': str(path.resolve()), 'raw_sha256': sha(path), 'accepted': False,
                    'status': 'captured_pending_review', 'hardware_pass': False,
                    'gate': artifact(args.gate), 'sources': {k: artifact(p) for k, p in files.items()},
                    'operations': artifact(args.output / 'operations.jsonl'),
                    'helper': artifact(HELPER), 'rtl_sha256': RTL_SHA}
            (args.output / ('diag%d.metadata.json' % camera)).write_text(json.dumps(meta, indent=2), encoding='utf-8')
        return 0
    except BaseException as error:
        if driver is not None and (io is None or io.poisoned):
            hold_buffers(error, args.output, driver, lock_fd, streams)
        # Protocol error after confirmed completion: no cleanup register submissions.
        if driver is not None:
            driver.close()
        (args.output / 'failure.json').write_text(json.dumps({'status': 'protocol_rejected',
            'error': repr(error), 'accepted': False, 'metadata_emitted': False}, indent=2))
        raise
    finally:
        for stream in streams:
            if not stream.closed:
                stream.close()
        os.close(lock_fd)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--execute', action='store_true')
    parser.add_argument('--gate', type=Path)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--timeout', type=float, default=2.0)
    args = parser.parse_args()
    try:
        require(math.isfinite(args.timeout) and 0 < args.timeout <= 30, 'Timeout must be 0..30 seconds')
        if args.execute:
            require(args.gate is not None and args.output is not None, '--execute requires --gate and --output')
            return execute(args)
        print(json.dumps(offline_check(), indent=2))
        return 0
    except Exception as error:
        print(json.dumps({'status': 'blocked', 'error': str(error), 'hardware_pass': False}), file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
