"""Independent build04 byte inventory; no build03 launch gate is imported."""
from pathlib import Path
import hashlib,json,re
HERE=Path(__file__).resolve().parent.parent
RUNTIME=HERE/'runtime'
BOARD=HERE.parent
def require(ok,message):
    if not ok:raise RuntimeError(message)
def sha(p):
    h=hashlib.sha256()
    with Path(p).open('rb') as f:
        for b in iter(lambda:f.read(4*1024*1024),b''):h.update(b)
    return h.hexdigest()
def load(p):return json.loads(Path(p).read_bytes())
def save(name,value):
    p=HERE/'evidence/runtime'/name;p.parent.mkdir(parents=True,exist_ok=True)
    require(not p.exists(),'Refuse overwrite evidence: '+str(p))
    p.write_text(json.dumps(value,indent=2,ensure_ascii=True)+'\n',encoding='ascii')
def verify():
    m=load(HERE/'manifest.json')
    require(m['root']==str(HERE) and m['candidate_id']==HERE.name,'Build04 root identity mismatch')
    require(len(m['local_hashes'])==741 and len(m['registered_sources'])==186,'741/186 inventory mismatch')
    actual={p.relative_to(HERE).as_posix() for d in ['rtl','inputs'] for p in (HERE/d).rglob('*') if p.is_file()}
    require(actual==set(m['full_source_copy_hashes']),'Unexpected or missing full copy inventory')
    require(set(m['local_hashes']).issubset(actual),'Missing 741 source inventory')
    for n,h in m['full_source_copy_hashes'].items():require(sha(HERE/n)==h,'Full source copy drift: '+n)
    for n,h in m['immutable_hashes'].items():
        if n!='project.pds':require(sha(HERE/n)==h,'Build04 immutable drift: '+n)
    raw=(HERE/'project.pds').read_bytes()
    initial=(HERE/'project_template.pds').read_bytes().replace(b'constraints_templates/',b'constraints_live/')
    def normalized(data):
        # Only PDS-maintained timestamps/state/output records may change.
        text=data.decode('ascii')
        text=re.sub(r'\(_comment "Generated by Fabric Compiler \(version on 2022\.2-SP6\.4<build 146967>\) at [^"]+"\)', '', text)
        for key in ['_timespec','_gci_state','_db_output','_output']:
            while True:
                found=re.search(r'\('+key+r'(?=\s)',text)
                if not found:break
                depth=0;quoted=False;end=None
                for i in range(found.start(),len(text)):
                    c=text[i]
                    if c=='"':quoted=not quoted
                    if not quoted:
                        if c=='(':depth+=1
                        elif c==')':
                            depth-=1
                            if depth==0:end=i+1;break
                require(end is not None,'Unbalanced project runtime record')
                text=text[:found.start()]+text[end:]
        return re.sub(r'\s+',' ',text).strip()
    require(normalized(raw)==normalized(initial),'Project change outside allowed PDS run metadata')
    regs=[x.decode('ascii') for x in re.findall(rb'\(_file "([^"]+)"',raw)]
    require([x for x in regs if x.startswith(('rtl/','inputs/'))]==m['registered_sources'],'186 actual source bindings changed')
    for n,h in m['protected_hashes'].items():require(sha(n)==h,'Protected original drift: '+n)
    for n,h in m['build03_full_hashes'].items():require(sha(Path(m['baseline_root'])/n)==h,'Frozen build03 drift: '+n)
    require(load(HERE/'sourcehash.json')==m['local_hashes'],'Build04 source ledger differs')
    return m
BAD_OPTIONS=re.compile(rb'Timing-4003|Timing-4006|STA-3016|(?:unknown|unsupported|unrecognized|ignor\w*).*?(?:option|argument|attribute)|(?:option|argument|attribute).*?not supported',re.I)
def log_errors(raw):
    return [x.decode('ascii','backslashreplace') for x in raw.splitlines() if x.startswith(b'E:') or re.match(rb'\s*(?:\*\*\s*)?(?:ERROR|FATAL)\b',x) or BAD_OPTIONS.search(x)]
